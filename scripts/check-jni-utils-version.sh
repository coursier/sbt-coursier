#!/usr/bin/env bash
set -euo pipefail

# Checks that the jni-utils version the LmNativeApi sources of lm-coursier come
# from (jniUtilsVersion in build.sbt) is the windows-jni-utils version pulled by
# the coursier version the sbt-coursier build depends on, and that these
# sources are the ones of jni-utils at that version. See the comment above
# jniUtilsVersion in build.sbt for why.
#
# The coursier modules are resolved from m2-repo, where
# scripts/publish-local-coursier.sh publishes them, so that script needs to
# have been run first.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
M2_REPO="${M2_REPO:-$ROOT/m2-repo}"

read_from_build() {
  local value
  value="$(sed -n "s/^\(def\|val\) $1 = \"\(.*\)\"$/\2/p" "$ROOT/build.sbt")"
  if [ "$(printf '%s\n' "$value" | grep -c .)" != "1" ]; then
    echo "Error: expected exactly one $1 definition in build.sbt, got:" 1>&2
    echo "$value" 1>&2
    exit 1
  fi
  echo "$value"
}

# the files copied from windows-jni-utils-lmcoursier/src/main/ in jni-utils
LM_COURSIER_MAIN="modules/lm-coursier/src/main"
VENDORED_FILES=(
  "java/lmcoursier/internal/jniutils/LmNativeApi.java"
  "resources/META-INF/native-image/io.get-coursier/jni-utils-lmcoursier/reflect-config.json"
)
JNI_UTILS_RAW_URL="${JNI_UTILS_RAW_URL:-https://raw.githubusercontent.com/coursier/jni-utils}"

# first line of the copied Java files, in place of the "Generated by the build…"
# line of the upstream ones
java_header() {
  echo "// Copied from windows-jni-utils-lmcoursier/src/main/$1 in https://github.com/coursier/jni-utils at tag v$EXPECTED - don't edit, see jniUtilsVersion in build.sbt"
}

EXPECTED="$(read_from_build jniUtilsVersion)"
COURSIER_VERSION="$(read_from_build coursierVersion0)"

# sbt 1.x plugins are Scala 2.12 ones, hence the Scala 2.12 flavour of coursier
# (like in publish-local-coursier.sh). The transitive dependencies of coursier
# are resolved from the default repositories (Maven Central, …), like the build does.
ACTUAL="$(
  cs resolve -r "file://$M2_REPO" "io.get-coursier:coursier_2.12:$COURSIER_VERSION" \
    | sed -n 's/^io\.get-coursier\.jniutils:windows-jni-utils:\([^:]*\).*$/\1/p' \
    | sort -u
)"

case "$(printf '%s\n' "$ACTUAL" | grep -c .)" in
  1) ;;
  0)
    echo "Error: windows-jni-utils not found among the dependencies of coursier $COURSIER_VERSION" 1>&2
    exit 1
    ;;
  *)
    echo "Error: several windows-jni-utils versions among the dependencies of coursier $COURSIER_VERSION:" 1>&2
    echo "$ACTUAL" 1>&2
    exit 1
    ;;
esac

if [ "$ACTUAL" != "$EXPECTED" ]; then
  echo "Error: coursier $COURSIER_VERSION depends on windows-jni-utils $ACTUAL," 1>&2
  echo "but the LmNativeApi sources of lm-coursier come from jni-utils $EXPECTED." 1>&2
  echo "Set jniUtilsVersion to \"$ACTUAL\" in build.sbt, and update the files below" 1>&2
  echo "from windows-jni-utils-lmcoursier/ in jni-utils at tag v$ACTUAL:" 1>&2
  for f in "${VENDORED_FILES[@]}"; do
    echo "  $LM_COURSIER_MAIN/$f" 1>&2
  done
  exit 1
fi

echo "coursier $COURSIER_VERSION depends on windows-jni-utils $ACTUAL, like the sbt-coursier build"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

DIFFERS=0
for f in "${VENDORED_FILES[@]}"; do
  URL="$JNI_UTILS_RAW_URL/v$EXPECTED/windows-jni-utils-lmcoursier/src/main/$f"
  curl -fsSL -o "$TMP_DIR/upstream" "$URL"
  case "$f" in
    *.java)
      # the first line of the upstream file says it's generated, which our copy
      # replaces with where it comes from
      { java_header "$f"; tail -n +2 "$TMP_DIR/upstream"; } > "$TMP_DIR/expected"
      ;;
    *)
      cp "$TMP_DIR/upstream" "$TMP_DIR/expected"
      ;;
  esac
  if ! diff -u "$TMP_DIR/expected" "$ROOT/$LM_COURSIER_MAIN/$f"; then
    echo "Error: $LM_COURSIER_MAIN/$f differs from $URL" 1>&2
    DIFFERS=1
  fi
done

if [ "$DIFFERS" != "0" ]; then
  exit 1
fi

echo "The LmNativeApi sources of lm-coursier are the ones of jni-utils $EXPECTED"
